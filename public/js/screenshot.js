/**
 * AbstractiFy Screenshot Exporter (Issue #03)
 * Converts DOM panels (Consensus, Matrix, Citation Graph) into crisp 2x PNG images
 * with AbstractiFy branding watermarks and automatic browser download.
 */

/**
 * Returns html2canvas configuration options adapted to current theme and display scaling.
 * @param {boolean} [isDark=false]
 * @returns {Object}
 */
export function getScreenshotOptions(isDark = false) {
    return {
        backgroundColor: isDark ? '#0F172A' : '#FDFAF6',
        scale: 2,
        useCORS: true,
        logging: false,
        allowTaint: false
    };
}

/**
 * Draws the standard AbstractiFy brand watermark in the bottom-right corner of an HTML canvas.
 * @param {HTMLCanvasElement} canvas
 * @param {Object} [options={}]
 * @param {boolean} [options.isDark=false]
 * @param {string} [options.text='Generated by AbstractiFy • abstractify1.netlify.app']
 * @returns {HTMLCanvasElement}
 */
export function drawWatermark(canvas, options = {}) {
    if (!canvas || typeof canvas.getContext !== 'function') return canvas;
    const ctx = canvas.getContext('2d');
    if (!ctx) return canvas;

    const isDark = Boolean(options.isDark);
    const text = options.text || 'Generated by AbstractiFy • abstractify1.netlify.app';

    ctx.save();
    ctx.font = 'bold 16px Inter, -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif';
    ctx.fillStyle = isDark ? 'rgba(255, 255, 255, 0.45)' : 'rgba(15, 23, 42, 0.45)';
    ctx.textBaseline = 'bottom';

    const textMetrics = ctx.measureText ? ctx.measureText(text) : { width: 380 };
    const textWidth = textMetrics.width || 380;
    const x = Math.max(16, canvas.width - textWidth - 24);
    const y = canvas.height - 18;

    ctx.fillText(text, x, y);
    ctx.restore();

    return canvas;
}

/**
 * Converts a DOM panel element into a high-resolution PNG screenshot with watermark and triggers download.
 * @param {HTMLElement|string} panel Panel element or DOM element ID
 * @param {string} [filename='AbstractiFy_Export']
 * @param {Object} [config={}]
 * @param {Function} [config.html2canvasFn] Optional html2canvas function override (for testing or CDN)
 * @param {boolean} [config.isDark]
 * @param {Function} [config.onComplete] Callback when download is triggered
 * @param {Function} [config.onError] Callback when error occurs
 * @returns {Promise<string|null>} Data URL of generated image, or null on error
 */
export async function exportPanelAsImage(panel, filename = 'AbstractiFy_Export', config = {}) {
    const el = typeof panel === 'string'
        ? (typeof document !== 'undefined' ? document.getElementById(panel) : null)
        : panel;

    if (!el) {
        const err = new Error(`Element "${panel}" not found for screenshot export.`);
        if (typeof config.onError === 'function') config.onError(err);
        return null;
    }

    const h2c = config.html2canvasFn || (typeof window !== 'undefined' ? window.html2canvas : null);
    if (!h2c || typeof h2c !== 'function') {
        const err = new Error('html2canvas library is not loaded.');
        if (typeof config.onError === 'function') config.onError(err);
        return null;
    }

    try {
        const isDark = config.isDark !== undefined
            ? config.isDark
            : (typeof document !== 'undefined' && document.documentElement.getAttribute('data-theme') === 'dark');

        const options = getScreenshotOptions(isDark);
        const canvas = await h2c(el, options);

        drawWatermark(canvas, { isDark });

        const dataUrl = canvas.toDataURL('image/png');
        const cleanName = String(filename || 'AbstractiFy_Panel').replace(/[^a-zA-Z0-9_-]/g, '_');
        const downloadName = `${cleanName}_${Date.now()}.png`;

        if (typeof document !== 'undefined') {
            const link = document.createElement('a');
            link.download = downloadName;
            link.href = dataUrl;
            document.body.appendChild(link);
            link.click();
            document.body.removeChild(link);
        }

        if (typeof config.onComplete === 'function') {
            config.onComplete({ filename: downloadName, dataUrl });
        }

        return dataUrl;
    } catch (error) {
        if (typeof config.onError === 'function') {
            config.onError(error);
        }
        return null;
    }
}
