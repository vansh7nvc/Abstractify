import { describe, it, expect, vi, beforeEach } from 'vitest';
import { getScreenshotOptions, drawWatermark, exportPanelAsImage } from '../js/screenshot.js';

describe('public/js/screenshot.js (Issue #03)', () => {
    describe('getScreenshotOptions', () => {
        it('returns slate dark background when isDark is true', () => {
            const opts = getScreenshotOptions(true);
            expect(opts.backgroundColor).toBe('#0F172A');
            expect(opts.scale).toBe(2);
            expect(opts.useCORS).toBe(true);
        });

        it('returns warm editorial background when isDark is false', () => {
            const opts = getScreenshotOptions(false);
            expect(opts.backgroundColor).toBe('#FDFAF6');
            expect(opts.scale).toBe(2);
            expect(opts.useCORS).toBe(true);
        });
    });

    describe('drawWatermark', () => {
        it('returns null or falsy canvas safely', () => {
            expect(drawWatermark(null)).toBeNull();
            expect(drawWatermark(undefined)).toBeUndefined();
        });

        it('draws watermark text onto canvas context', () => {
            const mockCtx = {
                save: vi.fn(),
                restore: vi.fn(),
                fillText: vi.fn(),
                measureText: vi.fn().mockReturnValue({ width: 300 }),
                font: '',
                fillStyle: '',
                textBaseline: ''
            };
            const mockCanvas = {
                width: 1200,
                height: 800,
                getContext: vi.fn().mockReturnValue(mockCtx)
            };

            const result = drawWatermark(mockCanvas, { isDark: true });
            expect(result).toBe(mockCanvas);
            expect(mockCtx.save).toHaveBeenCalled();
            expect(mockCtx.restore).toHaveBeenCalled();
            expect(mockCtx.fillText).toHaveBeenCalledWith(
                'Generated by AbstractiFy • abstractify1.netlify.app',
                expect.any(Number),
                expect.any(Number)
            );
            expect(mockCtx.fillStyle).toContain('rgba(255, 255, 255');
        });

        it('uses dark text fillStyle in light mode', () => {
            const mockCtx = {
                save: vi.fn(),
                restore: vi.fn(),
                fillText: vi.fn(),
                measureText: vi.fn().mockReturnValue({ width: 300 })
            };
            const mockCanvas = {
                width: 1000,
                height: 600,
                getContext: vi.fn().mockReturnValue(mockCtx)
            };

            drawWatermark(mockCanvas, { isDark: false });
            expect(mockCtx.fillStyle).toContain('rgba(15, 23, 42');
        });
    });

    describe('exportPanelAsImage', () => {
        let container;

        beforeEach(() => {
            document.body.innerHTML = '';
            container = document.createElement('div');
            container.id = 'test-panel';
            container.innerHTML = '<h2>Test Content</h2>';
            document.body.appendChild(container);
        });

        it('fails gracefully when panel element does not exist', async () => {
            const onError = vi.fn();
            const res = await exportPanelAsImage('non-existent-panel', 'Export', { onError });
            expect(res).toBeNull();
            expect(onError).toHaveBeenCalledWith(expect.any(Error));
        });

        it('fails gracefully when html2canvas function is missing', async () => {
            const onError = vi.fn();
            const res = await exportPanelAsImage(container, 'Export', { onError, html2canvasFn: null });
            expect(res).toBeNull();
            expect(onError).toHaveBeenCalledWith(expect.any(Error));
        });

        it('successfully captures element, draws watermark, and triggers download', async () => {
            const mockCtx = {
                save: vi.fn(),
                restore: vi.fn(),
                fillText: vi.fn(),
                measureText: vi.fn().mockReturnValue({ width: 250 })
            };
            const mockCanvas = {
                width: 1600,
                height: 900,
                getContext: vi.fn().mockReturnValue(mockCtx),
                toDataURL: vi.fn().mockReturnValue('data:image/png;base64,fakeimagedata')
            };

            const mockH2c = vi.fn().mockResolvedValue(mockCanvas);
            const onComplete = vi.fn();

            const clickSpy = vi.spyOn(HTMLAnchorElement.prototype, 'click').mockImplementation(() => {});

            const res = await exportPanelAsImage(container, 'AbstractiFy_Consensus', {
                html2canvasFn: mockH2c,
                isDark: true,
                onComplete
            });

            expect(mockH2c).toHaveBeenCalledWith(container, expect.objectContaining({ scale: 2, useCORS: true }));
            expect(mockCanvas.toDataURL).toHaveBeenCalledWith('image/png');
            expect(clickSpy).toHaveBeenCalled();
            expect(onComplete).toHaveBeenCalledWith(expect.objectContaining({
                filename: expect.stringMatching(/AbstractiFy_Consensus_\d+\.png/),
                dataUrl: 'data:image/png;base64,fakeimagedata'
            }));
            expect(res).toBe('data:image/png;base64,fakeimagedata');

            clickSpy.mockRestore();
        });

        it('calls onError callback if html2canvas throws an error', async () => {
            const mockH2c = vi.fn().mockRejectedValue(new Error('Canvas rendering failed'));
            const onError = vi.fn();

            const res = await exportPanelAsImage(container, 'Export', {
                html2canvasFn: mockH2c,
                onError
            });

            expect(res).toBeNull();
            expect(onError).toHaveBeenCalledWith(expect.any(Error));
        });
    });
});
